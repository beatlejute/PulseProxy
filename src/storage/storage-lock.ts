/**
 * Сериализация записей по ключу storage в пределах одного JS-контекста.
 *
 * У chrome.storage нет транзакций и compare-and-swap, а все мутации репозиториев —
 * это read-modify-write (getAll → изменить → setAll). Две конкурентные цепочки на
 * одном ключе (например, переименование пресета по blur и клик «Save domains»)
 * читают один и тот же снапшот, и второй setAll затирает первый. Общий per-key
 * лок выстраивает такие цепочки в очередь.
 *
 * Ограничение: лок работает только внутри ОДНОГО контекста (popup ИЛИ background).
 * Межконтекстные гонки (popup vs background service worker) им не покрываются —
 * у них разные инстансы модуля; для этого нужен отдельный механизм.
 */

const locks = new Map<string, Promise<unknown>>();

/**
 * Выполняет `fn` эксклюзивно относительно других вызовов withStorageLock с тем же
 * ключом: следующий начнётся только после того, как предыдущий полностью завершится
 * (в т.ч. если завершился ошибкой). Значение/ошибка `fn` пробрасывается вызывающему.
 */
export async function withStorageLock<T>(key: string, fn: () => Promise<T>): Promise<T> {
    const previous = locks.get(key) ?? Promise.resolve();

    // Ждём предыдущую операцию по ключу независимо от её исхода, затем запускаем свою.
    const run = previous.then(fn, fn);

    // В цепочку лока кладём «обезвреженную» версию (без проброса ошибки), чтобы
    // отказ одной операции не ронял всю последующую очередь по ключу.
    locks.set(key, run.then(() => undefined, () => undefined));

    return run;
}
